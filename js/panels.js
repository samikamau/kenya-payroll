async function generatePayslipPDF(empId){
  await ensurePdfLibsLoaded();
  const c = state.clients[state.activeClient];
  const emp = c.employees.find(e => e.id === empId);
  const r = calcEmployee(emp);
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ unit:'pt', format: [297.64, 841.89] }); // A4 height kept as-is; width halved, per instruction
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const left = 32; const right = pageWidth - 32; let y = 40;
  const [br, bg, bb] = hexToRgb(c.brandColor || '#123C36');

  const line = (label, value, opts={}) => {
    doc.setFont('helvetica', opts.bold ? 'bold' : 'normal');
    doc.setFontSize(opts.size || 9.5);
    doc.text(label, left, y);
    doc.text(String(value), right, y, { align:'right' });
    y += opts.gap || 14;
  };
  const section = (title) => {
    y += 5;
    doc.setDrawColor(180); doc.line(left, y, right, y); y += 15;
    doc.setFont('helvetica','bold'); doc.setFontSize(10);
    doc.setTextColor(br, bg, bb);
    doc.text(title.toUpperCase(), left, y);
    doc.setTextColor(20,20,20);
    y += 15;
  };
  const centerX = pageWidth / 2;

  // Header block: logo, company name, "PAYSLIP" title, pay period - all centered.
  y += 6;
  if(c.logoDataUrl){
    try{
      const logoW = Math.min(c.logoSize || 60, 70);
      const logoH = logoW * (c.logoAspect || 0.75);
      doc.addImage(c.logoDataUrl, 'PNG', centerX - logoW / 2, y, logoW, logoH);
      y += logoH + 10;
    }catch(e){ /* ignore malformed image, don't block payslip generation */ }
  }

  doc.setFont('helvetica','bold'); doc.setFontSize(15);
  doc.setTextColor(br, bg, bb);
  doc.text(c.name || 'Payslip', centerX, y, { align:'center' });
  y += 17;

  doc.setFont('helvetica','bold'); doc.setFontSize(11);
  doc.setTextColor(20,20,20);
  doc.text('PAYSLIP', centerX, y, { align:'center' });
  y += 13;

  doc.setFont('helvetica','normal'); doc.setFontSize(9.5);
  doc.setTextColor(90,90,90);
  doc.text(`Pay Period: ${c.period || '-'}`, centerX, y, { align:'center' });
  doc.setTextColor(20,20,20);
  y += 16;

  // Bold rule, then a dotted rule beneath it, closing out the header block.
  doc.setLineWidth(1.4); doc.setDrawColor(20,20,20);
  doc.line(left, y, right, y);
  y += 5;
  doc.setLineWidth(0.75); doc.setLineDashPattern([1.5, 1.5], 0);
  doc.line(left, y, right, y);
  doc.setLineDashPattern([], 0); doc.setLineWidth(1);
  y += 16;

  // Remaining identifying fields, left-aligned as before.
  line('Employer PIN', c.kraPin || '-');
  line('Employee Name', emp.name || 'Unnamed');
  line('Payroll Number', emp.payrollNumber || '-');
  line('KRA PIN', emp.pin || '-');
  y += 4;

  section('Earnings');
  line('Basic salary', fmt(emp.basic));
  line('Allowances', fmt(emp.allowances));
  if(emp.overtimePay) line('Overtime pay', fmt(emp.overtimePay));
  (emp.bonusItems||[]).forEach(b => {
    if(b.amount) line(b.description ? `${b.type}: ${b.description}` : b.type, fmt(b.amount));
  });
  line('Gross pay', fmt(r.gross), { bold:true });

  section('Statutory deductions');
  line('NSSF (Tier I + II)', fmt(r.nssfEmployee));
  line('SHIF (2.75%)', fmt(r.shif));
  line('Housing Levy (1.5%)', fmt(r.ahlEmployee));
  if(r.voluntaryPension) line('Voluntary pension', fmt(r.voluntaryPension));
  y += 4;
  line('Taxable pay', fmt(r.taxable));
  line('Tax on taxable pay', fmt(r.grossTax));
  line('Less: personal relief', `-${fmt(RATES.personalRelief)}`);
  if(r.insuranceRelief) line('Less: insurance relief', `-${fmt(r.insuranceRelief)}`);
  line('PAYE', fmt(r.paye), { bold:true });

  const hasOtherDeductions = (emp.deductionItems||[]).some(d => d.amount);
  if(hasOtherDeductions){
    section('Other deductions');
    (emp.deductionItems||[]).forEach(d => {
      if(d.amount) line(d.description ? `${d.type}: ${d.description}` : d.type, fmt(d.amount));
    });
    line('Total other deductions', fmt(r.otherDeduct), { bold:true });
  }

  section('Net pay');
  doc.setFont('helvetica','bold'); doc.setFontSize(13);
  doc.setTextColor(br, bg, bb);
  doc.text('Take-home pay', left, y);
  doc.text(`KES ${fmt(r.net)}`, right, y, { align:'right' });
  doc.setTextColor(20,20,20);
  y += 26;

  doc.setFont('helvetica','italic'); doc.setFontSize(7.5); doc.setTextColor(140,140,140);
  doc.text('Generated by Edhafu Payroll. Verify statutory figures against current KRA/NSSF/SHA rates.', left, pageHeight - 24, { maxWidth: pageWidth - left * 2 });

  return { doc, filename: `${(emp.name||'employee').replace(/\s+/g,'_')}_payslip_${c.period||''}.pdf` };
}

async function downloadPayslipPDF(empId){
  const c = state.clients[state.activeClient];
  if(!requireAccess(c)) return;
  const { doc, filename } = await generatePayslipPDF(empId);
  doc.save(filename);
}

async function emailPayslip(empId, evt){
  const c = state.clients[state.activeClient];
  if(!requireAccess(c)) return;
  const emp = c.employees.find(e => e.id === empId);
  if(!emp.email){
    const addr = prompt('Enter this employee\'s email address:');
    if(!addr) return;
    await updateEmployeeField(empId, 'email', addr);
    emp.email = addr;
  }
  const { doc } = await generatePayslipPDF(empId);
  const pdfBase64 = doc.output('datauristring').split(',')[1];
  const btn = evt.target;
  const originalText = btn.textContent;
  btn.textContent = 'Sending...'; btn.disabled = true;
  try{
    const { data, error } = await sb.functions.invoke('send-payslip', {
      body: {
        to: emp.email,
        employeeName: emp.name,
        companyName: c.name,
        period: c.period,
        pdfBase64
      }
    });
    if(error) throw error;
    alert(`Payslip sent to ${emp.email}`);
  } catch(err){
    let detail = err.message || 'the email function may not be set up yet.';
    try{
      if(err.context && typeof err.context.json === 'function'){
        const body = await err.context.json();
        if(body && body.error) detail = body.error;
      }
    }catch(_){}
    alert('Could not send email: ' + detail);
  } finally {
    btn.textContent = originalText; btn.disabled = false;
  }
}

