/* ---------------- Multi-user company sharing ----------------
   Frontend hides/shows the panel for convenience only — the real security is the RLS
   policies in migration_012 (has_company_access). Even if this panel were shown to someone
   who shouldn't manage sharing, the database itself would reject their insert/delete.
------------------------------------------------------------------------------------- */
let shareListCache = {}; // companyId -> array of { id, email }
async function toggleSharePanel(){
  const c = state.clients[state.activeClient];
  if(!c || !state.activeClient) return;
  await loadShares(state.activeClient);
  openPanel(renderSharePanel(c));
}
async function loadShares(companyId){
  const { data, error } = await sb.from('company_access').select('*').eq('company_id', companyId);
  if(error){ console.error(error); shareListCache[companyId] = []; return; }
  shareListCache[companyId] = (data||[]).map(r => ({ id: r.id, email: r.granted_email, userId: r.user_id }));
}
async function shareCompanyWithColleague(){
  const email = prompt('Enter the email of a colleague who already has an account — they\'ll get full access to this client:');
  if(!email) return;
  const cleanEmail = email.trim().toLowerCase();
  const { data: foundId, error: lookupError } = await sb.rpc('get_user_id_by_email', { lookup_email: cleanEmail });
  if(lookupError){ alert('Could not look up that email: ' + lookupError.message); return; }
  if(!foundId){ alert(`No account found for ${cleanEmail}. Ask your colleague to sign up first (using the same sign-in screen), then try sharing again.`); return; }
  const { data: userData } = await sb.auth.getUser();
  const { error } = await sb.from('company_access').insert({
    company_id: state.activeClient, user_id: foundId, granted_email: cleanEmail, granted_by: userData?.user?.id
  });
  if(error){ alert('Could not share: ' + error.message); return; }
  logAudit('Client shared', `Access granted to ${cleanEmail}`);
  await loadShares(state.activeClient);
  openPanel(renderSharePanel(state.clients[state.activeClient]));
}
async function revokeShare(accessId, email){
  if(!confirm(`Remove ${email}'s access to this client?`)) return;
  const { error } = await sb.from('company_access').delete().eq('id', accessId);
  if(error){ alert('Could not revoke access: ' + error.message); return; }
  logAudit('Client access revoked', `Removed access for ${email}`);
  await loadShares(state.activeClient);
  openPanel(renderSharePanel(state.clients[state.activeClient]));
}
function renderSharePanel(c){
  const shares = shareListCache[state.activeClient] || [];
  const isOwner = c.ownerId === state.currentUserId;
  return `
    <div class="settings-panel">
      <h3 style="font-size:13px;color:var(--gold);font-family:'Inter',sans-serif;font-weight:600;margin-bottom:4px;">Share &amp; access — ${esc(c.name) || 'this client'}</h3>
      <div style="font-size:11.5px;color:var(--muted);margin-bottom:14px;">${isOwner ? 'People with access to this client (full access, same as yours).' : 'You have shared access to this client. Only the owner can manage who else has access.'}</div>
      ${shares.length === 0 ? `<div style="color:var(--muted);font-size:12.5px;padding:6px 0;">Not shared with anyone yet.</div>` : ''}
      ${shares.map(s => `
        <div style="display:flex;justify-content:space-between;align-items:center;padding:7px 0;border-bottom:1px solid var(--line);font-size:12.5px;">
          <span>${esc(s.email)}</span>
          ${isOwner ? `<span style="color:#EF4444;cursor:pointer;font-size:11.5px;" onclick="revokeShare('${s.id}', '${esc(s.email)}')">Remove</span>` : ''}
        </div>
      `).join('')}
      ${isOwner ? `<button class="btn primary" style="margin-top:14px;" onclick="shareCompanyWithColleague()">+ Share with a colleague</button>` : ''}
    </div>
  `;
}
